/** User IDs and sender-chat IDs are separate native identities, even when their numbers match. */
internal fun ChatSnapshot.senderAvatar(message: ChatMessage): MediaFile? = when {
    message.senderIsChat -> knownChats.firstOrNull { it.id == message.senderId }?.avatar
    message.senderId == account?.userId -> account?.avatar
    else -> senderAvatars[message.senderId]
}
